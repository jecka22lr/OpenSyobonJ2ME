#!/bin/bash
# Builds OpenSyobonJ2ME jars/jads from the Open Syobon Action source.
#
#   ./build.sh                    MIDP 2.0, 240x210 view, music + effects
#   LITE=1 ./build.sh             same, effects only
#   SCALE=3 ./build.sh            MIDP 2.0, 160x140 view (176x208, 176x220, 208x208)
#   SCALE=4 ./build.sh            MIDP 2.0, 120x105 view (128x128, 128x160)
#   MIDP=1 SCALE=4 ./build.sh     MIDP 1.0 / CLDC 1.0, 120x105, silent, under 64 KB
#   MIDP=1 SCALE=3 ./build.sh     MIDP 1.0 / CLDC 1.0, 160x140, effects if the
#                                 phone has MMAPI (add MUSIC=1 for the music too)
#
# SCALE 3 and 4 (MIDP 2.0) are effects-only and leave out the three long jingles.
set -e
cd "$(dirname "$0")"
[ -d deps/OpenSyobonAction ] || ./tools/fetch-deps.sh
mkdir -p build
unset JAVA_TOOL_OPTIONS
S=${SYOBON_SRC:-deps/OpenSyobonAction}
FJ=${FREEJ2ME_CLASSES:-deps/freej2me/build/classes}   # MIDP API to compile against
PG=${PROGUARD:-deps/proguard-7.4.2/lib/proguard.jar}
SCALE=${SCALE:-2}
MIDP=${MIDP:-2}
NAME=OpenSyobonJ2ME
FONT=12
SOUND=true
case $MIDP$SCALE in
  22) [ -n "$LITE" ] && NAME=OpenSyobonJ2ME-lite ;;
  23) NAME=OpenSyobonJ2ME-208; LITE=1; SMALLSE=1; FONT=10 ;;
  24) NAME=OpenSyobonJ2ME-128; LITE=1; SMALLSE=1; FONT=10 ;;
  13) NAME=OpenSyobonJ2ME-midp1-176; FONT=10; [ -z "$MUSIC" ] && LITE=1 ;;
  14) NAME=OpenSyobonJ2ME-midp1-128; FONT=10; SOUND=false ;;
  *) echo "unsupported MIDP=$MIDP SCALE=$SCALE"; exit 1 ;;
esac
if [ $MIDP = 1 ]; then
  PROFILE=MIDP-1.0; CONFIG=CLDC-1.0; TARGET=1.1
  SRC="src/java/syobon/*.java src/midp1/syobon/*.java"
else
  PROFILE=MIDP-2.0; CONFIG=CLDC-1.1; TARGET=1.4
  SRC="src/java/syobon/*.java src/midp2/syobon/*.java"
fi
VERSION=1.0.0

# 1. game logic: C++ -> Java, plus generated config and trig table
rm -rf res && mkdir -p res/st
python3 tools/extract_stages.py $S/main.cpp res/st build/logic.cpp > /dev/null
cat res/st/s{0..16}.bin > res/st.bin
python3 tools/convert.py build/logic.cpp $S/main.h $S/loadg.cpp src/java/syobon/G.java
python3 tools/patch.py src/java/syobon/G.java
MIDP1=false; [ $MIDP = 1 ] && MIDP1=true
python3 - $SCALE $MIDP1 $SOUND <<'EOF'
import sys, math
k, midp1, sound = sys.argv[1:4]
open('src/java/syobon/Cfg.java', 'w').write(
    'package syobon;\n\n/** Generated by build.sh. */\nfinal class Cfg {\n'
    '    static final int K = %s;\n    static final boolean MIDP1 = %s;\n'
    '    static final boolean SOUND = %s;\n}\n' % (k, midp1, sound))
# cos for 0..90 degrees in half-degree steps, scaled by 16384, packed as chars
vals = [round(math.cos(math.radians(i / 2)) * 16384) for i in range(181)]
lit = ''.join('\\u%04x' % v for v in vals)
open('src/java/syobon/Tab.java', 'w').write(
    'package syobon;\n\n/** Generated by build.sh: integer trig table (CLDC 1.0 has no floats). */\n'
    'final class Tab {\n    static final String COS = "%s";\n}\n' % lit)
EOF

# 2. compile (Java 8 bytecode, no StringBuilder/boxing/class literals allowed)
rm -rf build/cls build/rec build/stubs && mkdir -p build/cls build/rec build/stubs
javac -nowarn -d build/stubs -cp $FJ src/stubs/com/nokia/mid/ui/FullCanvas.java
if ! javac -nowarn -encoding UTF-8 -source 8 -target 8 -cp $FJ:build/stubs -d build/cls $SRC > build/javac.log 2>&1; then
  grep -v "^warning" build/javac.log; exit 1
fi
if javap -c -p -cp build/cls $(cd build/cls && ls syobon/*.class | sed 's/\.class//;s#/#.#') | grep -q "StringBuilder\|Integer.valueOf\|java/util/\(Array\|Collection\|List\|Map\|HashMap\|Iterator\|Objects\|Set\)\|ldc.*class "; then
  echo "non-CLDC API used"; exit 1
fi

# 3. sprites: record rects from loadg(), then reduce
javac -nowarn -source 8 -target 8 -cp build/cls:$FJ -d build/rec tools/rec/syobon/Rec.java 2>/dev/null
java -cp build/rec:build/cls:$FJ syobon.Rec > build/rects.txt
mkdir -p res/g
python3 tools/sprites.py $S/res res/g build/rects.txt $SCALE
if [ $MIDP = 1 ]; then
  # MIDP 1.0 cannot flip images at draw time: ship flipped copies
  python3 - <<'EOF'
from PIL import Image
for n in ["player", "brock", "item", "teki", "brock2", "omake", "omake2"]:
    im = Image.open('res/g/%s.png' % n)
    t = im.info.get('transparency')
    kw = {'transparency': t} if t is not None else {}
    im.transpose(Image.FLIP_LEFT_RIGHT).save('res/g/%s_m.png' % n, optimize=True, **kw)
    if n == 'teki':
        im.transpose(Image.FLIP_TOP_BOTTOM).save('res/g/%s_v.png' % n, optimize=True, **kw)
EOF
fi

# 4. font and translation
python3 tools/font.py $S/res/sazanami-gothic.ttf res/f.bin $FONT $SRC tools/en.txt
python3 tools/lang.py tools/en.txt src/java/syobon/G.java res/en.bin

# 5. audio: 8 kHz 8-bit mono WAV, plain 44-byte headers
mkdir -p res/a
WAV="-ac 1 -ar 8000 -c:a pcm_u8 -map_metadata -1 -fflags +bitexact -flags:a +bitexact"
if [ $SOUND = true ]; then
  if [ -z "$LITE" ]; then
    i=1
    for n in field dungeon star4 castle puyo; do
      extra=""; [ $n = dungeon ] && extra="-t 19.072"   # file holds the loop twice
      ffmpeg -v error -y -i $S/BGM/$n.ogg $extra -af "highpass=f=60,lowpass=f=3800,loudnorm=I=-14:TP=-1:LRA=11" $WAV res/a/b$i.wav
      i=$((i+1))
    done
  fi
  declare -A SE=([1]=jump [3]=brockbreak [4]=coin [5]=humi [6]=koura [7]=dokan [8]=brockkinoko [9]=powerup [10]=kirra [11]=goal [12]=death [13]=Pswitch [14]=jumpBlock [15]=hintBlock [16]=4-clear [17]=allclear [18]=tekifire)
  # the long jingles (goal, 4-clear, all-clear) cost ~110 KB; small builds skip them
  if [ -n "$SMALLSE" ]; then unset 'SE[11]' 'SE[16]' 'SE[17]'; fi
  for k in "${!SE[@]}"; do
    ffmpeg -v error -y -i $S/SE/${SE[$k]}.ogg -af "highpass=f=60,lowpass=f=3800,volume=1.4,alimiter=limit=0.95" $WAV res/a/s$k.wav
  done
fi

# 6. icon
python3 - $SCALE <<'EOF'
import sys
from PIL import Image
k = int(sys.argv[1])
# the standing frame (source x 124..154)
im = Image.open('res/g/player.png').convert('RGBA').crop((124 // k, 0, -(-154 // k), -(-36 // k)))
ic = Image.new('RGBA', (im.width + 1, im.height), (0, 0, 0, 0)); ic.paste(im, (0, 0))
ic.save('res/icon.png')
EOF

# 7. jar, shrink + preverify
rm -rf build/jar && mkdir -p build/jar && cp -r build/cls/* build/jar/
cp -r res/g res/st.bin res/f.bin res/en.bin res/icon.png build/jar/
[ -n "$(ls res/a)" ] && cp -r res/a build/jar/
cat > build/MANIFEST.MF <<EOF
MIDlet-1: OpenSyobonJ2ME, /icon.png, syobon.Main
MIDlet-Name: OpenSyobonJ2ME
MIDlet-Vendor: Chiku (port: Jecka)
MIDlet-Version: $VERSION
MIDlet-Icon: /icon.png
MicroEdition-Configuration: $CONFIG
MicroEdition-Profile: $PROFILE
EOF
(cd build/jar && jar cfm ../raw.jar ../MANIFEST.MF .)
cat > build/pg.cfg <<EOF
-injars raw.jar
-outjars $NAME.jar
-libraryjars api.jar
-libraryjars stubs
-microedition
-target $TARGET
-dontusemixedcaseclassnames
-allowaccessmodification
-overloadaggressively
-repackageclasses ''
-optimizationpasses 3
-keep public class syobon.Main
-keep public class syobon.CvN { public <init>(); }
-dontnote
-dontwarn syobon.CvN
EOF
# library jar for proguard = MIDP API classes from FreeJ2ME (javax.microedition only) + JDK base
(cd $FJ && jar cf $OLDPWD/build/api.jar javax)
echo "-libraryjars <java.home>/jmods/java.base.jmod(!**.jar;!module-info.class)" >> build/pg.cfg
java -jar $PG @build/pg.cfg > build/pg.log 2>&1 || { cat build/pg.log; exit 1; }

# 8. check the shipped classes only use what the target profile has
rm -rf build/chk && mkdir -p build/chk && (cd build/chk && unzip -q ../$NAME.jar)
CLS=$(cd build/chk && find . -name "*.class" | sed 's#^\./##;s/\.class$//;s#/#.#g')
javap -c -p -cp build/chk $CLS > build/chk.txt
if [ $MIDP = 1 ]; then
  BAD="drawRegion\|drawRGB\|getRGB\|fillTriangle\|setFullScreenMode\|lcdui/game\|sizeChanged"
  [ $SOUND = false ] && BAD="$BAD\|javax/microedition/media"
  # CLDC 1.0: no floating point anywhere
  BAD="$BAD\|java/lang/Float\|java/lang/Double\|\bd[a-z]*load\|\bf[a-z]*load\|[ilfd]2[df]\b\|[df]2[il]\b\|dconst\|fconst\|ldc2_w.*double\|ldc.*float"
  if grep -q "$BAD" build/chk.txt; then
    grep -n "$BAD" build/chk.txt | head; echo "MIDP 1.0 / CLDC 1.0 check failed"; exit 1
  fi
fi

JARSIZE=$(stat -c%s build/$NAME.jar)
cat > build/$NAME.jad <<EOF
MIDlet-1: OpenSyobonJ2ME, /icon.png, syobon.Main
MIDlet-Name: OpenSyobonJ2ME
MIDlet-Vendor: Chiku (port: Jecka)
MIDlet-Version: $VERSION
MIDlet-Icon: /icon.png
MIDlet-Jar-URL: $NAME.jar
MIDlet-Jar-Size: $JARSIZE
MicroEdition-Configuration: $CONFIG
MicroEdition-Profile: $PROFILE
EOF
echo "built build/$NAME.jar ($JARSIZE bytes)"
if [ $MIDP$SCALE = 14 ] && [ $JARSIZE -gt 65536 ]; then echo "WARNING: over the 64 KB limit of old Series 40 phones"; fi
